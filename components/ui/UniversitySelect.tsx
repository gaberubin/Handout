interface Props {
  value: string;
  onChange: (v: string) => void;
  disabled?: boolean;
  placeholder?: string;
  inputStyle?: React.CSSProperties;
}

export function UniversitySelect({ value, onChange, disabled, placeholder = 'Start typing your university…', inputStyle }: Props) {
  const [open, setOpen] = useState(false);
  const [highlight, setHighlight] = useState(0);
  const wrapperRef = useRef<HTMLDivElement>(null);

  const filtered = value.length === 0
    ? UNIVERSITIES.slice(0, 8)
    : UNIVERSITIES.filter(u => u.toLowerCase().includes(value.toLowerCase())).slice(0, 12);

  useEffect(() => {
    function handler(e: MouseEvent) {
      if (wrapperRef.current && !wrapperRef.current.contains(e.target as Node)) setOpen(false);
    }
    document.addEventListener('mousedown', handler);
    return () => document.removeEventListener('mousedown', handler);
  }, []);

  function selectItem(uni: string) { onChange(uni); setOpen(false); setHighlight(0); }

  function handleKeyDown(e: React.KeyboardEvent) {
    if (!open) { if (e.key === 'ArrowDown' || e.key === 'Enter') setOpen(true); return; }
    if (e.key === 'ArrowDown') { e.preventDefault(); setHighlight(h => Math.min(h + 1, filtered.length - 1)); }
    else if (e.key === 'ArrowUp') { e.preventDefault(); setHighlight(h => Math.max(h - 1, 0)); }
    else if (e.key === 'Enter') { e.preventDefault(); if (filtered[highlight]) selectItem(filtered[highlight]); else if (value.trim()) selectItem(value.trim()); }
    else if (e.key === 'Escape') setOpen(false);
  }

  const base: React.CSSProperties = {
    width: '100%', height: 44, padding: '0 14px',
    background: 'rgba(18,36,28,0.04)', border: '1px solid rgba(18,36,28,0.12)',
    borderRadius: 10, color: '#12241C', fontSize: 14, boxSizing: 'border-box', outline: 'none',
  };

  return (
    <div ref={wrapperRef} style={{ position: 'relative' }}>
      <input
        type="text" value={value}
        onChange={e => { onChange(e.target.value); setOpen(true); setHighlight(0); }}
        onFocus={() => setOpen(true)}
        onKeyDown={handleKeyDown}
        disabled={disabled}
        placeholder={placeholder}
        autoComplete="off"
        style={{ ...base, ...inputStyle }}
      />

      {open && filtered.length > 0 && (
        <div style={{ position: 'absolute', top: 'calc(100% + 5px)', left: 0, right: 0, background: '#fff', border: '1px solid rgba(18,36,28,0.12)', borderRadius: 12, boxShadow: '0 8px 28px rgba(18,36,28,0.18)', maxHeight: 280, overflowY: 'auto', zIndex: 300 }}>
          {filtered.map((uni, i) => (
            <div key={uni} onMouseDown={e => { e.preventDefault(); selectItem(uni); }} onMouseEnter={() => setHighlight(i)}
              style={{ padding: '10px 14px', cursor: 'pointer', fontSize: 14, display: 'flex', alignItems: 'center', gap: 8, background: i === highlight ? 'rgba(18,161,80,0.08)' : 'transparent', color: i === highlight ? '#12A150' : '#12241C', borderBottom: i < filtered.length - 1 ? '1px solid rgba(18,36,28,0.04)' : 'none', transition: 'background 0.1s' }}>
              <span style={{ opacity: 0.5, flexShrink: 0 }}>🎓</span>
              <span>{uni}</span>
            </div>
          ))}
        </div>
      )}

      {open && value.length > 0 && filtered.length === 0 && (
        <div style={{ position: 'absolute', top: 'calc(100% + 5px)', left: 0, right: 0, background: '#fff', border: '1px solid rgba(18,36,28,0.12)', borderRadius: 12, padding: '12px 14px', zIndex: 300, fontSize: 13, color: '#4c6157' }}>
          No match — press Enter to save "<span style={{ color: '#12A150' }}>{value}</span>".
        </div>
      )}
    </div>
  );
}
